// Precompiles the old site's Handlebars views (../src/views, same files the Express
// server renders) into src/templates.js. Workers cannot compile templates at run
// time (no eval), but can run precompiled ones with handlebars/runtime.
import Handlebars from 'handlebars';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const views = join(root, '..', 'src', 'views');
const files = { layout: 'layouts/main.handlebars', tweet: 'tweet.handlebars', news: 'news.handlebars' };
const parts = Object.entries(files).map(
  ([name, file]) => `  ${name}: ${Handlebars.precompile(readFileSync(join(views, file), 'utf8'))},`,
);
writeFileSync(
  join(root, 'src', 'templates.js'),
  `// Generated by scripts/build-templates.mjs from src/views; do not edit\nexport default {\n${parts.join('\n')}\n};\n`,
);
console.log(`precompiled ${parts.length} templates`);
